// Command demogen writes the demo collections and the benchmark cases:
// invented documents for typical PersonalRAG use cases, usable in the app
// (add a folder of demo/) and by the agent benchmark, which checks answers
// against demo/cases.yaml.
//
//	go run ./cmd/demogen            # writes demo/
//	go run ./cmd/demogen -out DIR
//
// The output is deterministic; a test fails when demo/ is out of date.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/goccy/go-yaml"
)

func main() {
	out := flag.String("out", "demo", "output directory")
	flag.Parse()
	if err := generate(*out); err != nil {
		log.Fatal(err)
	}
	fmt.Println("demo corpus written to", *out)
}

// Case is one benchmark question with what a correct answer contains.
type Case struct {
	ID       string `yaml:"id"`
	Folder   string `yaml:"folder"` // collection folder below demo/
	Mode     string `yaml:"mode"`   // search | answer | agent
	Question string `yaml:"question"`
	Expect   Expect `yaml:"expect"`
	Note     string `yaml:"note,omitempty"`
}

// Expect lists what a correct result contains. Counts and documents are
// exact; Contains are case-insensitive substrings of the answer.
type Expect struct {
	Documents   []string      `yaml:"documents,omitempty"`   // all must be among the hits or cited sources
	Distractors []string      `yaml:"distractors,omitempty"` // should not be returned (reported, not required)
	Contains    []string      `yaml:"contains,omitempty"`
	Counts      yaml.MapSlice `yaml:"counts,omitempty"`      // person → sessions attended
	NotCounted  []string      `yaml:"not_counted,omitempty"` // people who must not be counted (guests)
	// Concepts are groups of alternative terms (any language); at least
	// MinConcepts groups must occur in the answer.
	Concepts     [][]string `yaml:"concepts,omitempty"`
	MinConcepts  int        `yaml:"min_concepts,omitempty"`
	Excludes     []string   `yaml:"excludes,omitempty"`      // terms the answer must not contain
	MinQuestions int        `yaml:"min_questions,omitempty"` // question marks the answer must contain
}

// Cases is the file format of demo/cases.yaml.
type Cases struct {
	Version int    `yaml:"version"`
	Cases   []Case `yaml:"cases"`
}

func generate(out string) error {
	ss := buildSessions()
	offers := buildOffers()
	for _, d := range []string{"protokolle", "angebote", "skript", "pruefung"} {
		dir := filepath.Join(out, d)
		if err := os.RemoveAll(dir); err != nil {
			return err
		}
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	if err := writeProtocols(filepath.Join(out, "protokolle"), ss); err != nil {
		return err
	}
	if err := writeOffers(filepath.Join(out, "angebote"), offers); err != nil {
		return err
	}
	if err := writeScript(filepath.Join(out, "skript")); err != nil {
		return err
	}
	if err := writeRules(filepath.Join(out, "pruefung")); err != nil {
		return err
	}
	data, err := yaml.Marshal(buildCases(ss, offers))
	if err != nil {
		return err
	}
	header := "# Generated by go run ./cmd/demogen; do not edit by hand.\n"
	return os.WriteFile(filepath.Join(out, "cases.yaml"), append([]byte(header), data...), 0o644)
}

func buildCases(ss []session, offers []offer) Cases {
	counts := attendance(ss)
	names := make([]string, 0, len(counts))
	for n := range counts {
		names = append(names, n)
	}
	slices.Sort(names)
	var cm yaml.MapSlice
	for _, n := range names {
		cm = append(cm, yaml.MapItem{Key: n, Value: counts[n]})
	}

	var guests45 []string
	for _, s := range ss {
		if s.number == 45 {
			for _, g := range s.printedGuests() {
				guests45 = append(guests45, lastName(personName(g)))
			}
		}
	}
	var guests []string
	for _, s := range ss {
		for _, g := range s.printedGuests() {
			if n := personName(g); !slices.Contains(guests, n) {
				guests = append(guests, n)
			}
		}
	}
	slices.Sort(guests)
	hits, lookalike := carFiles(offers)
	file := func(n int) string { return fmt.Sprintf("protokoll-%d.pdf", n) }

	return Cases{Version: 1, Cases: []Case{
		{
			ID: "protokolle-teilnahme", Folder: "protokolle", Mode: "agent",
			Question: "Erstelle mir aus allen Protokollen des Vereinsausschusses eine Liste der Teilnehmerinnen und Teilnehmer (nur die Anwesenden, keine Gäste und keine Entschuldigten) und zähle, an wie vielen Sitzungen jede Person teilgenommen hat.",
			Expect:   Expect{Counts: cm, NotCounted: guests},
			Note:     fmt.Sprintf("Participants stand in the left column, guests and the excused in the right one. Protocol %d is a scan (OCR). The deputy counts for himself, not for the member he stands in for.", scanSession),
		},
		{
			ID: "protokolle-beitragsordnung", Folder: "protokolle", Mode: "answer",
			Question: "In welcher Sitzung wurde die neue Beitragsordnung beschlossen?",
			Expect:   Expect{Documents: []string{file(48)}, Distractors: []string{file(45)}, Contains: []string{"48"}},
			Note:     "Session 45 had only a first reading without a decision.",
		},
		{
			ID: "protokolle-haushalt", Folder: "protokolle", Mode: "answer",
			Question: "In welchen Sitzungen hat der Vereinsausschuss Beschlüsse zum Haushalt gefasst?",
			Expect:   Expect{Documents: []string{file(42), file(51)}, Distractors: []string{file(46)}, Contains: []string{"42", "51"}},
			Note:     "Session 46 has a cash report without a decision.",
		},
		{
			ID: "protokolle-gaeste", Folder: "protokolle", Mode: "answer",
			Question: "Wer war in der 45. Sitzung des Vereinsausschusses als Gast anwesend?",
			Expect:   Expect{Documents: []string{file(45)}, Contains: guests45},
		},
		{
			ID: "protokolle-scan", Folder: "protokolle", Mode: "search",
			Question: "Neubau des Vereinsheims",
			Expect:   Expect{Documents: []string{file(scanSession)}},
			Note:     "Only the scanned protocol is about the new clubhouse; it needs OCR.",
		},
		{
			ID: "angebote-dienstwagen", Folder: "angebote", Mode: "answer",
			Question: "Zeige mir alle Vertragsangebote, in denen ein Dienstwagen angeboten wird.",
			Expect:   Expect{Documents: hits, Distractors: lookalike},
			Note:     fmt.Sprintf("Nine offers, worded Dienstwagen, Firmenwagen or Dienstfahrzeug; offer %d mentions it only on page 2. Distractors offer bike leasing, tickets or parking. Use \"show more\" until all are found.", lateCar),
		},
		{
			ID: "angebote-dienstwagen-suche", Folder: "angebote", Mode: "search",
			Question: "Dienstwagen",
			Expect:   Expect{Documents: hits, Distractors: lookalike},
		},
		{
			ID: "skript-pruefungsfragen", Folder: "skript", Mode: "agent",
			Question: "Erstelle 5 Prüfungsfragen mit Musterlösungen zu Kapitel 3 des Vorlesungsskripts Database Systems.",
			Expect: Expect{
				Concepts: [][]string{
					{"ACID"}, {"serializab", "serialisierbar"}, {"two-phase locking", "Zwei-Phasen-Sperr", "2PL"},
					{"deadlock", "Verklemmung"}, {"wait-for", "Wartegraph"}, {"isolation level", "Isolationsstufe", "Isolationslevel"},
					{"write-ahead", "WAL"}, {"undo", "redo"}, {"conflict graph", "precedence graph", "Konfliktgraph"},
				},
				MinConcepts:  4,
				Excludes:     []string{"B+-", "ANSI/SPARC", "hash join", "Normalform", "normal form", "two-phase commit", "Zwei-Phasen-Commit", "2PC"},
				MinQuestions: 5,
			},
			Note: "The notes are in English, the task in German. Chapter 3 is about transactions; terms from other chapters (B+-trees, normal forms, two-phase commit) must not appear.",
		},
		{
			ID: "skript-2pl-seite", Folder: "skript", Mode: "answer",
			Question: "Auf welcher Seite des Skripts wird das Zwei-Phasen-Sperrprotokoll (Two-Phase Locking) erklärt?",
			Expect: Expect{Documents: []string{scriptFile}, MinConcepts: 1, Concepts: [][]string{func() []string {
				p := scriptSectionPage("3.3")
				return []string{fmt.Sprintf("Seite %d", p), fmt.Sprintf("S. %d", p), fmt.Sprintf("page %d", p), fmt.Sprintf("Seiten %d", p)}
			}()}},
			Note: "Two-phase commit (chapter 6) is a different protocol.",
		},
		{
			ID: "pruefung-regeln", Folder: "pruefung", Mode: "agent",
			Question: "Prüfe die Bachelorarbeit von Jana Meier gegen die Regeln aus der Prüfungsordnung und dem Leitfaden für Abschlussarbeiten. Nenne für jede Regel, ob sie eingehalten ist, mit Begründung.",
			Expect: Expect{
				Concepts: [][]string{
					{fmt.Sprint(thesisBodyPages)},
					{"Eigenständigkeitserklärung", "Selbstständigkeitserklärung", "Selbständigkeitserklärung", "eidesstattliche Erklärung"},
					{fmt.Sprintf("%d Quellen", thesisSources), fmt.Sprintf("%d Einträge", thesisSources), fmt.Sprintf("%d Literatur", thesisSources), "zwölf", fmt.Sprintf("nur %d", thesisSources), fmt.Sprintf("%d Titel", thesisSources), fmt.Sprintf("%d Referenzen", thesisSources), fmt.Sprintf("%d Werke", thesisSources), fmt.Sprintf("%d Publikationen", thesisSources)},
				},
				MinConcepts: 3,
			},
			Note: fmt.Sprintf("Three violations: %d pages instead of at most 60, no declaration of authorship, %d sources instead of at least 20. Structure, abstracts, citation style, language and figure captions are fine; reporting them as violations is wrong (check by hand).", thesisBodyPages, thesisSources),
		},
		{
			ID: "pruefung-umfang", Folder: "pruefung", Mode: "answer",
			Question: "Wie viele Seiten darf eine Bachelorarbeit höchstens umfassen?",
			Expect:   Expect{Documents: []string{regulationsFile}, Contains: []string{"60"}},
		},
	}}
}

func lastName(name string) string { return name[strings.LastIndex(name, " ")+1:] }
