// Command demogen writes the demo collections and the benchmark cases:
// invented documents for typical PersonalRAG use cases, usable in the app
// (add a folder of demo/) and by the agent benchmark, which checks answers
// against demo/cases.yaml.
//
//	go run ./cmd/demogen            # writes demo/
//	go run ./cmd/demogen -out DIR
//
// The output is deterministic; a test fails when demo/ is out of date.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/goccy/go-yaml"
)

func main() {
	out := flag.String("out", "demo", "output directory")
	flag.Parse()
	if err := generate(*out); err != nil {
		log.Fatal(err)
	}
	fmt.Println("demo corpus written to", *out)
}

// Case is one benchmark question with what a correct answer contains.
type Case struct {
	ID       string `yaml:"id"`
	Folder   string `yaml:"folder"` // collection folder below demo/
	Mode     string `yaml:"mode"`   // search | answer | agent
	Question string `yaml:"question"`
	Expect   Expect `yaml:"expect"`
	Note     string `yaml:"note,omitempty"`
}

// Expect lists what a correct result contains. Counts and documents are
// exact; Contains are case-insensitive substrings of the answer.
type Expect struct {
	Documents   []string      `yaml:"documents,omitempty"`   // all must be among the hits or cited sources
	Distractors []string      `yaml:"distractors,omitempty"` // should not be returned (reported, not required)
	Contains    []string      `yaml:"contains,omitempty"`
	Counts      yaml.MapSlice `yaml:"counts,omitempty"`      // person → sessions attended
	NotCounted  []string      `yaml:"not_counted,omitempty"` // people who must not be counted (guests)
}

// Cases is the file format of demo/cases.yaml.
type Cases struct {
	Version int    `yaml:"version"`
	Cases   []Case `yaml:"cases"`
}

func generate(out string) error {
	ss := buildSessions()
	offers := buildOffers()
	for _, d := range []string{"protokolle", "angebote"} {
		dir := filepath.Join(out, d)
		if err := os.RemoveAll(dir); err != nil {
			return err
		}
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	if err := writeProtocols(filepath.Join(out, "protokolle"), ss); err != nil {
		return err
	}
	if err := writeOffers(filepath.Join(out, "angebote"), offers); err != nil {
		return err
	}
	data, err := yaml.Marshal(buildCases(ss, offers))
	if err != nil {
		return err
	}
	header := "# Generated by go run ./cmd/demogen; do not edit by hand.\n"
	return os.WriteFile(filepath.Join(out, "cases.yaml"), append([]byte(header), data...), 0o644)
}

func buildCases(ss []session, offers []offer) Cases {
	counts := attendance(ss)
	names := make([]string, 0, len(counts))
	for n := range counts {
		names = append(names, n)
	}
	slices.Sort(names)
	var cm yaml.MapSlice
	for _, n := range names {
		cm = append(cm, yaml.MapItem{Key: n, Value: counts[n]})
	}

	var guests45 []string
	for _, s := range ss {
		if s.number == 45 {
			for _, g := range s.printedGuests() {
				guests45 = append(guests45, lastName(personName(g)))
			}
		}
	}
	var guests []string
	for _, s := range ss {
		for _, g := range s.printedGuests() {
			if n := personName(g); !slices.Contains(guests, n) {
				guests = append(guests, n)
			}
		}
	}
	slices.Sort(guests)
	hits, lookalike := equipmentFiles(offers)
	file := func(n int) string { return fmt.Sprintf("protokoll-%d.pdf", n) }

	return Cases{Version: 1, Cases: []Case{
		{
			ID: "protokolle-teilnahme", Folder: "protokolle", Mode: "agent",
			Question: "Erstelle mir aus allen Protokollen der Sammlung eine Liste der Teilnehmerinnen und Teilnehmer (nur die Anwesenden, keine Gäste und keine Entschuldigten) und zähle, an wie vielen Sitzungen jede Person teilgenommen hat.",
			Expect:   Expect{Counts: cm, NotCounted: guests},
			Note:     fmt.Sprintf("Participants stand in the left column, guests and the excused in the right one. Protocol %d is a scan (OCR). The deputy counts for himself, not for the member he stands in for.", scanSession),
		},
		{
			ID: "protokolle-bibliotheksordnung", Folder: "protokolle", Mode: "answer",
			Question: "In welcher Sitzung wurde die Neufassung der Bibliotheksordnung beschlossen?",
			Expect:   Expect{Documents: []string{file(48)}, Distractors: []string{file(45)}, Contains: []string{"48"}},
			Note:     "Session 45 had only a first reading without a decision.",
		},
		{
			ID: "protokolle-haushalt", Folder: "protokolle", Mode: "answer",
			Question: "In welchen Sitzungen hat der Senat Beschlüsse zum Haushalt gefasst?",
			Expect:   Expect{Documents: []string{file(42), file(51)}, Distractors: []string{file(46)}, Contains: []string{"42", "51"}},
			Note:     "Session 46 has a budget report without a decision.",
		},
		{
			ID: "protokolle-gaeste", Folder: "protokolle", Mode: "answer",
			Question: "Wer war in der 45. Sitzung des Senats als Gast anwesend?",
			Expect:   Expect{Documents: []string{file(45)}, Contains: guests45},
		},
		{
			ID: "protokolle-scan", Folder: "protokolle", Mode: "search",
			Question: "Neubau der Mensa",
			Expect:   Expect{Documents: []string{file(scanSession)}},
			Note:     "Only the scanned protocol mentions the canteen; it needs OCR.",
		},
		{
			ID: "angebote-grossgeraete", Folder: "angebote", Mode: "answer",
			Question: "Zeige mir alle Berufungsangebote, in denen Großgeräte erwähnt werden.",
			Expect:   Expect{Documents: hits, Distractors: lookalike},
			Note:     fmt.Sprintf("Nine offers; offer %d mentions it only on page 2. Distractors mention small equipment or open-plan labs. Use \"show more\" until all are found.", lateEquipment),
		},
		{
			ID: "angebote-grossgeraete-suche", Folder: "angebote", Mode: "search",
			Question: "Großgeräte",
			Expect:   Expect{Documents: hits, Distractors: lookalike},
		},
	}}
}

func lastName(name string) string { return name[strings.LastIndex(name, " ")+1:] }
